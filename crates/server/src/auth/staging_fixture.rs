/// Whether this configuration says coffer is on localhost, the only place the seed belongs.
pub(crate) fn on_localhost(config: &Config) -> bool {
    config.public_url.domain() == Some("localhost")
}

/// Whether `passkey` has a seeded credential's id or public key.
pub(super) fn is_staging_fixture(passkey: &Passkey) -> bool {
    let id = passkey.cred_id().as_ref();
    if id == STAGING_ADMIN_CREDENTIAL_ID || id == STAGING_MEMBER_CREDENTIAL_ID {
        return true;
    }
    let COSEKeyType::EC_EC2(key) = &passkey.get_public_key().key else {
        return false;
    };
    STAGING_PUBLIC_KEYS
        .iter()
        .any(|(x, y)| key.x.as_ref() == x.as_slice() && key.y.as_ref() == y.as_slice())
}
